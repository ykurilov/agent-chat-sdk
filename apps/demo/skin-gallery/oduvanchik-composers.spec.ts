import { expect, test } from "@playwright/test";
import { expectNoHorizontalOverflow, saveScreenshot, screenshotFolder } from "../e2e/support/screen";

const folder = screenshotFolder("agent-chat-oduvanchik-composers");
test("три вида: ввод, файлы/проект, каталог, настройки, Стоп, темы и шторка телефона", async ({ page }) => {
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.setViewportSize({ width: 1560, height: 1050 });
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.clock.install({ time: new Date("2026-10-22T00:00:00Z") });
  await page.clock.pauseAt(new Date("2026-10-22T00:00:01Z"));
  await page.goto("/oduvanchik-composers.html");
  const compact = page.locator('section[data-variant="compact"]');
  const standard = page.locator('section[data-variant="standard"]');
  const extended = page.locator('section[data-variant="extended"]');
  await expect(extended.getByRole("button", { name: /Модель: DeepSeek/ })).toBeEnabled();
  await saveScreenshot(page, folder, "oduvanchik-composers-empty-light");
  const compactField = compact.getByRole("textbox");
  await compactField.fill("   ");
  await compactField.press("Enter");
  await expect(compact.getByRole("button", { name: "Отправить" })).toBeDisabled();
  await compactField.fill("План урока");
  await compactField.press("Shift+Enter");
  await expect(compactField).toHaveValue("План урока\n");
  await compactField.press("Enter");
  await compact.getByRole("button", { name: "Остановить" }).click();
  await expect(compact.getByText("Работа остановлена.")).toBeVisible();
  await standard.getByRole("button", { name: "Файл", exact: true }).click();
  await standard.getByRole("button", { name: "Лендинг вебинара", exact: true }).click();
  await expect(standard.locator(".oduvanchik-field-files")).toContainText("Лендинг вебинара");
  await standard.locator('input[type="file"]').setInputFiles({ name: "brief.txt", mimeType: "text/plain", buffer: Buffer.from("Brief") });
  await expect(standard.locator(".oduvanchik-field-files")).toContainText("brief.txt");
  await standard.getByRole("button", { name: "@ Мастерская" }).click();
  await expect(standard.getByRole("button", { name: "@ Лендинг вебинара" })).toBeVisible();
  await extended.getByRole("button", { name: /Модель:/ }).click();
  const modelPanel = page.getByRole("dialog", { name: "Модель", exact: true });
  await modelPanel.locator(".oduvanchik-model-option").filter({ hasText: "GLM 5.3 Flash" }).click();
  await modelPanel.getByRole("button", { name: "Together AI", exact: true }).click();
  await expect(modelPanel.getByText("Текстовые задачи", { exact: true })).toBeVisible();
  await expect(modelPanel.getByText("Текст и изображения", { exact: true })).toBeVisible();
  await saveScreenshot(page, folder, "oduvanchik-composers-catalog-light");
  await modelPanel.getByRole("searchbox").fill("GPT 6 Luna");
  await modelPanel.locator(".oduvanchik-model-option").click();
  await expect(extended.getByRole("button", { name: "Модель: GPT 6 Luna" })).toBeVisible();
  await expect(modelPanel.getByRole("button", { name: "OpenRouter", exact: true })).toBeVisible();
  await page.keyboard.press("Escape");
  await extended.getByRole("button", { name: "Рассуждения", exact: true }).click();
  await page.getByRole("dialog").getByRole("button", { name: "Высоко", exact: true }).click();
  await page.keyboard.press("Escape");
  await extended.getByRole("button", { name: "Инструменты", exact: true }).click();
  await page.getByRole("switch", { name: "Поиск", exact: true }).uncheck();
  await expect(extended.getByRole("button", { name: "Инструменты", exact: true })).toContainText("2");
  await page.keyboard.press("Escape");
  await extended.getByRole("textbox").fill("Собери план рассылки");
  await extended.getByRole("textbox").press("Enter");
  await expect(extended.getByRole("button", { name: "Остановить" })).toBeVisible();
  await expect(extended.getByRole("button", { name: /Модель:/ })).toBeDisabled();
  await expect(extended.locator("[data-work-live]")).toContainText("Прочитал материалы проекта");
  await saveScreenshot(page, folder, "oduvanchik-composers-working-light");
  await page.clock.runFor(2000);
  await expect(extended.locator(".oduvanchik-answer-meta")).toContainText("GPT 6 Luna · OpenRouter · Высоко");
  await extended.getByRole("button", { name: /Думал 3/ }).click();
  await expect(extended.getByText(/Изучил материалы проекта/)).toBeVisible();
  await saveScreenshot(page, folder, "oduvanchik-composers-light");
  await page.getByRole("button", { name: "Светлая / тёмная" }).click();
  await expect(extended.locator(".oduvanchik-field")).toHaveCSS("background-color", "rgb(22, 22, 22)");
  await saveScreenshot(page, folder, "oduvanchik-composers-dark");
  await page.setViewportSize({ width: 390, height: 844 });
  await expectNoHorizontalOverflow(page);
  await saveScreenshot(page, folder, "oduvanchik-composers-phone-dark");
  await extended.getByRole("button", { name: /Модель:/ }).click();
  const sheet = page.getByRole("dialog", { name: "Настройки ответа" });
  await expect(sheet.getByRole("switch", { name: "Показывать ход мысли" })).toBeVisible();
  await expect(sheet.getByRole("switch", { name: "Файлы", exact: true })).toBeVisible();
  await expect(sheet.getByRole("button", { name: "Готово" })).toBeVisible();
  await saveScreenshot(page, folder, "oduvanchik-composers-phone-sheet-dark");
  await sheet.getByRole("switch", { name: "Показывать ход мысли" }).uncheck();
  await sheet.getByRole("button", { name: "Готово" }).click();
  await expect(extended.getByRole("button", { name: /Думал/ })).toHaveCount(0);
  await page.getByRole("button", { name: "Светлая / тёмная" }).click();
  await saveScreenshot(page, folder, "oduvanchik-composers-phone-light");
  for (const name of ["Сжатое", "Обычное", "Расширенное"]) {
    await page.getByRole("navigation", { name: "Вид поля" }).getByRole("button", { name, exact: true }).click();
    await expectNoHorizontalOverflow(page);
  }
  await page.setViewportSize({ width: 320, height: 700 });
  await expectNoHorizontalOverflow(page);
  expect(errors).toEqual([]);
});
