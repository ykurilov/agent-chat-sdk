import { expect, test } from "@playwright/test";
import { expectNoHorizontalOverflow, saveScreenshot, screenshotFolder } from "../e2e/support/screen";

const folder = screenshotFolder("agent-chat-skin-oduvanchik");

test("Одуванчик: новый чат, шаги v28, файл, подтверждение и отправка; темы и телефон", async ({ page }) => {
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto("/oduvanchik.html");
  await expect(page.getByRole("heading", { name: "Чем помочь?" })).toBeVisible();
  await expect(page.locator("canvas")).toHaveCount(2);
  await saveScreenshot(page, folder, "oduvanchik-welcome-light");
  await page.getByRole("button", { name: "Написать План рассылки к вебинару" }).click();
  await expect(page.locator("[data-work-live]")).toContainText("Пишу структуру писем");
  await saveScreenshot(page, folder, "oduvanchik-working-light");
  await page.getByRole("button", { name: "Проверить расписание" }).click();
  await expect(page.locator("[data-work-step]")).toHaveCount(3);
  await expect(page.locator("[data-step-icon]").first()).toHaveAttribute("data-step-icon", "read");
  await expect(page.getByRole("link", { name: "План рассылки.md" })).toHaveAttribute("download", "План рассылки.md");
  await expect(page.locator('[data-tool-state="awaiting-approval"]')).toBeVisible();
  await expectNoHorizontalOverflow(page);
  const send = page.getByRole("button", { name: "Отправить", exact: true });
  await page.getByRole("textbox", { name: "Сообщение" }).fill("Изменить время отправки");
  await expect(send).toBeEnabled();
  await expect(send).toHaveCSS("background-color", "rgb(20, 20, 20)");
  await saveScreenshot(page, folder, "oduvanchik-desktop-light");
  await page.getByRole("button", { name: "Светлая / тёмная" }).click();
  await expect(send).toHaveCSS("background-color", "rgb(242, 242, 240)");
  await saveScreenshot(page, folder, "oduvanchik-desktop-dark");
  await page.setViewportSize({ width: 390, height: 844 });
  await expectNoHorizontalOverflow(page);
  await saveScreenshot(page, folder, "oduvanchik-phone-dark");
  await page.getByRole("button", { name: "Сменить тему" }).click();
  await expect(send).toHaveCSS("background-color", "rgb(20, 20, 20)");
  await saveScreenshot(page, folder, "oduvanchik-phone-light");
  await page.getByRole("button", { name: "Разрешить", exact: true }).click();
  await expect(page.getByRole("status", { name: "" }).filter({ hasText: "Решение принято" })).toBeVisible();
  // Enter and button both respect canSubmit; an IME Enter must keep the draft.
  const field = page.getByRole("textbox", { name: "Сообщение" });
  await field.fill("Правка после подтверждения");
  await field.dispatchEvent("keydown", { key: "Enter", isComposing: true });
  await expect(field).toHaveValue("Правка после подтверждения");
  await field.press("Enter");
  await expect(field).toHaveValue("");
  await page.getByRole("button", { name: "Проверить расписание" }).click();
  await expect(send).toBeDisabled();
  await page.locator('input[type="file"]').setInputFiles({ name: "brief.txt", mimeType: "text/plain", buffer: Buffer.from("brief") });
  await expect(send).toBeEnabled();
  await page.getByRole("button", { name: /brief.txt/ }).click();
  await expect(send).toBeDisabled();
  await page.setViewportSize({ width: 320, height: 700 });
  await expectNoHorizontalOverflow(page);
  await page.goto("/oduvanchik.html?theme=system");
  await page.emulateMedia({ colorScheme: "dark", reducedMotion: "reduce" });
  await expect(page.locator(".oduvanchik-chat").first()).toHaveCSS("background-color", "rgb(15, 15, 15)");
  expect(errors).toEqual([]);
});
