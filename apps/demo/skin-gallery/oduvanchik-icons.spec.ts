import { expect, test } from "@playwright/test";
import { expectNoHorizontalOverflow, saveScreenshot, screenshotFolder } from "../e2e/support/screen";

const folder = screenshotFolder("agent-chat-oduvanchik-phosphor");
test("Phosphor through public skin components: Markdown, notices, voice menu and memory dialog", async ({ page, context }) => {
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  page.on("console", message => { if (message.type() === "error") errors.push(message.text()); });
  await context.grantPermissions(["clipboard-read", "clipboard-write"]);
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.setViewportSize({ width: 1200, height: 1000 });
  await page.goto("/oduvanchik-icons.html");
  const noLucide = async () => {
    await expect(page.locator("svg.lucide")).toHaveCount(0);
    for (const svg of await page.locator("svg").all()) await expect(svg).toHaveAttribute("viewBox", "0 0 256 256");
  };
  await noLucide();
  const copy = page.getByRole("button", { name: "Скопировать код" });
  await copy.focus(); await copy.press("Enter");
  await expect(page.getByRole("button", { name: "Скопировано" })).toBeVisible();
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe("const answer = 42;");
  await page.getByRole("button", { name: /Повторить/ }).click();
  await expect(page.getByRole("status").filter({ hasText: "Повтор принят" })).toBeVisible();
  await page.getByRole("button", { name: "Голос: Анна" }).click();
  await expect(page.getByRole("menuitemradio", { name: "Анна" })).toHaveAttribute("aria-checked", "true");
  await noLucide();
  await saveScreenshot(page, folder, "oduvanchik-phosphor-menu-light");
  await page.getByRole("menuitemradio", { name: "Борис" }).click();
  await expect(page.getByRole("button", { name: "Голос: Борис" })).toBeFocused();
  await page.getByRole("button", { name: "Удалить запись памяти" }).click();
  await expect(page.getByRole("dialog")).toBeVisible(); await noLucide();
  await saveScreenshot(page, folder, "oduvanchik-phosphor-dialog-light");
  await page.getByRole("button", { name: "Закрыть", exact: true }).click();
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await saveScreenshot(page, folder, "oduvanchik-phosphor-light");
  await page.getByRole("button", { name: "Светлая / тёмная" }).click();
  await saveScreenshot(page, folder, "oduvanchik-phosphor-dark");
  await page.setViewportSize({ width: 390, height: 844 }); await expectNoHorizontalOverflow(page);
  await page.getByRole("button", { name: "Голос: Борис" }).click(); await noLucide();
  await saveScreenshot(page, folder, "oduvanchik-phosphor-phone-menu-dark");
  await page.keyboard.press("Escape");
  await page.getByRole("button", { name: "Удалить запись памяти" }).click();
  await saveScreenshot(page, folder, "oduvanchik-phosphor-phone-dialog-dark");
  await page.keyboard.press("Escape");
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await page.getByRole("button", { name: "Светлая / тёмная" }).click();
  await saveScreenshot(page, folder, "oduvanchik-phosphor-phone-light");
  await noLucide(); expect(errors).toEqual([]);
});
