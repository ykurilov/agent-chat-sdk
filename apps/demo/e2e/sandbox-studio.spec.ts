import { expect, test } from "./support/own-server";
import { lastAnswer, send } from "./support/chat";
import { signInToSandbox } from "./support/sandbox";
import { expectNoHorizontalOverflow, saveScreenshot, screenshotFolder } from "./support/screen";
const folder = screenshotFolder("agent-chat-studio-live");

test("default Studio: real journal/parameters, editing, history, responsive state and explicit Tandem", async ({ page }) => {
  const errors: string[] = [];
  const taskPolls: string[] = [];
  page.on("request", (request) => { if (/\/api\/sandbox\/[^/]+\/tasks/.test(new URL(request.url()).pathname)) taskPolls.push(request.url()); });
  page.on("pageerror", (error) => errors.push(error.message));
  page.on("console", (message) => { if (message.type() === "error") errors.push(message.text()); });
  await signInToSandbox(page, "", "default");
  await expect(page.getByRole("heading", { name: "С чего начнём?" })).toBeVisible();
  await expect(page.locator(".yk-studio")).toHaveCount(1);
  await send(page, "Сколько времени в Токио и в Москве и какая разница?");
  await expect(lastAnswer(page)).toHaveAttribute("data-status", "complete");
  const journal = page.getByRole("region", { name: "Журнал", exact: true });
  const row = journal.getByRole("button", { name: /Ответ ·/ }).first();
  await row.click();
  await expect(journal.getByRole("heading", { name: "Сообщения" })).toBeVisible();
  await lastAnswer(page).getByRole("button", { name: "Изменить ответ" }).click();
  const editor = page.getByRole("region", { name: "Правка ответа" });
  await editor.getByRole("textbox", { name: "Текст ответа" }).fill("Разница - ровно шесть часов.");
  await editor.getByRole("button", { name: "Сохранить", exact: true }).click();
  await expect(lastAnswer(page)).toContainText("ровно шесть часов");
  await page.getByRole("button", { name: "Инструкция чата" }).click();
  const instruction = page.getByRole("dialog", { name: "Инструкция чата" });
  await instruction.getByRole("textbox", { name: "Текст инструкции" }).fill("Отвечай одним словом.");
  await instruction.getByRole("button", { name: "Сохранить", exact: true }).click();
  await expect(instruction.getByRole("button", { name: "Сохранить", exact: true })).toBeDisabled();
  await instruction.getByRole("button", { name: "Отмена", exact: true }).click();
  const model = page.getByRole("button", { name: /^Модель:/ });
  await model.click();
  await page.locator(".oduvanchik-model-option").filter({ hasText: "GPT 6 Luna" }).click();
  await expect(model).toContainText("GPT 6 Luna");
  await page.keyboard.press("Escape");
  await send(page, "Привет");
  await expect(lastAnswer(page)).toHaveAttribute("data-status", "complete");
  const turn = page.getByRole("combobox", { name: "Выбор хода" });
  await turn.selectOption({ label: "Ответ 2" });
  await row.click();
  await expect(row).toHaveAttribute("aria-expanded", "true");
  const selectedTurn = await turn.inputValue();
  await page.setViewportSize({ width: 390, height: 844 });
  const openJournal = page.getByRole("button", { name: "Открыть журнал" });
  await openJournal.click();
  const sheet = page.getByRole("dialog", { name: "Журнал", exact: true });
  await expect(sheet.getByRole("combobox", { name: "Выбор хода" })).toHaveValue(selectedTurn);
  await expect(sheet.getByRole("button", { name: /Ответ ·/ }).first()).toHaveAttribute("aria-expanded", "true");
  await saveScreenshot(page, folder, "studio-live-phone-journal");
  await page.keyboard.press("Escape");
  await expect(openJournal).toBeFocused();
  await page.getByRole("button", { name: "Чаты", exact: true }).click();
  const history = page.getByRole("dialog", { name: "Чаты", exact: true });
  await expect(history.getByRole("navigation", { name: "Чаты" })).toBeVisible();
  await history.getByRole("button", { name: "Готово", exact: true }).click();
  await expectNoHorizontalOverflow(page);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await saveScreenshot(page, folder, "studio-live-desktop");
  await page.goto("/sandbox?skin=tandem");
  await expect(page.getByRole("textbox", { name: "Сообщение" })).toBeVisible();
  await expect(page.locator(".yk-studio")).toHaveCount(0);
  expect(await page.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue("--yk-bg").trim())).toBe("");
  expect(taskPolls).toEqual([]);
  expect(errors).toEqual([]);
});
