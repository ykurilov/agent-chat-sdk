/**
 * Знак жизни идущего ответа (FR-060): несколько копий сервера на одной базе отличают ответ упавшей копии от живого
 * ответа соседа по времени последнего знака (`StoredMessage.alive`; время ставит хранилище по своим часам).
 *
 * Ход пишет знак при вставке ответа и с каждой промежуточной записью, а в тишине (инструмент думает, модель молчит,
 * пауза перед повтором) — лёгкой отметкой `markAnswerAlive` раз в `ANSWER_ALIVE_EVERY_MS`. Пределы ожидания хода на знак не влияют:
 * таймер знака идёт и пока ход ждёт инструмент или модель.
 */
export const ANSWER_ALIVE_EVERY_MS = 5_000;

/** Ответ без знака жизни дольше этого — брошен упавшей копией: три пропущенных знака подряд. */
export const ANSWER_STALE_AFTER_MS = 3 * ANSWER_ALIVE_EVERY_MS;

/**
 * Как часто служба ищет брошенные ответы после первого `recoverInterruptedAnswers`. Вместе с порогом это окно, когда
 * ответ упавшей копии ещё выглядит идущим: 15–20 с. Запрос дешёвый — по частичному индексу идущих ответов.
 */
export const STALE_ANSWERS_SWEEP_EVERY_MS = 5_000;
