const numberFormat = new Intl.NumberFormat("ru-RU");

/** Число токенов для текста модели: с пробелом-разделителем, как в задании («20 000»). */
function tokens(count: number): string {
  return numberFormat.format(count).replace(/\s/g, " ");
}

/**
 * Задание сжатия, последнее сообщение запроса. Приложение может заменить его целиком (`instruction`).
 * Текст постоянный: зависит только от потолка.
 */
export function compactionTask(input: { summaryCeilingTokens: number; instruction?: string }): string {
  if (input.instruction !== undefined) return input.instruction;
  return `Сделай сводку всей переписки выше, чтобы можно было продолжить работу без старых сообщений.

Если в начале переписки уже есть сводка, не дописывай к ней, а перепиши её целиком вместе с новыми сообщениями: получится одна сводка.

Сводка — Markdown с такими разделами, в таком порядке, названия не менять:
## Цель
## Решения
## Факты
## Файлы и результаты
## Незакрытые задачи
## Где остановились

Сохраняй точные значения, которые понадобятся снова: имена, пути, числа, адреса, команды. Прикреплённые файлы (блоки <attachment name="…"> и картинки) назови в разделе «Файлы и результаты» по имени и коротко запиши, что в них важно: сами файлы после сжатия в запрос не попадут. Не выдумывай ничего, чего не было в переписке. Не вызывай инструменты. Объём сводки — не больше ${tokens(input.summaryCeilingTokens)} токенов.

Ответь только сводкой, без вступления.`;
}

/** Просьба ужать сводку, которая вышла больше потолка. */
export function shrinkRequest(input: { summaryTokens: number; summaryCeilingTokens: number }): string {
  return `Сводка получилась на ${tokens(input.summaryTokens)} токенов, а потолок — ${tokens(input.summaryCeilingTokens)}. Перепиши её короче, с теми же разделами: убери подробности, которые легко восстановить, оставь точные значения. Ответь только сводкой.`;
}

/** Как сводка выглядит для модели: пересказ ушедшей части переписки в постоянном обрамлении. */
export function summaryFrame(summary: string): string {
  return `<conversation_summary>
Ниже пересказ прежней части этой переписки. Сами старые сообщения убраны из контекста, чтобы он не переполнился; опирайся на пересказ как на память о том, что было раньше.

${summary}
</conversation_summary>`;
}
