import type { AgentFlow } from "../../format/flow-format";

// Человек пишет после конца разговора (→ В6, режим `reply`). Отдельная постоянная инструкция: агент знает, что
// программа закончилась, и отвечает по общей части сценария, без нод. Приложение перехватывает через `admit`
// (решение `ended`) или свой `beforeTurn`; режим `silent` до модели не доходит.

const AFTER_END_RULES = `# Программа закончилась

Программа разговора закончилась. Человек пишет уже после её конца.
- Ответь на его вопрос по общей части ниже: коротко и по делу.
- Не веди по шагам программы, не начинай её заново и не продавай повторно.
- Первым не пиши. Переходов больше нет: «flow_exit» не вызывай.
- Пришло служебное сообщение «Срок программы вышел» — попрощайся одним сообщением: коротко подведи итог и скажи, что дальше.`;

/** Постоянные правила после конца разговора: вместо `flowRules`, когда чат закончен. От дня и места не зависят. */
export function afterEndRules(flow: AgentFlow): string {
  const shared = flow.common.trim();
  return shared ? `${AFTER_END_RULES}\n\n## Общее\n${shared}` : AFTER_END_RULES;
}
