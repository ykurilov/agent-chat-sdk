import { hasSideTasks } from "../../engine/side-tasks";
import type { FlowRulePart } from "./rule-part";

// Попутные задачи: как с ними обращаться. Сами задачи и сколько попыток осталось — в хвосте шага, а не здесь: текст
// правила зависит только от того, есть ли у сценария попутные задачи, и инструкция под кэш не меняется от попыток.

/** Имя инструмента попутных задач (`runtime/side-task-tool.ts`). */
const SIDE_TASK_TOOL = "flow_side_task";

const SIDE_TASK_RULES = `## Попутные задачи

В конце запроса иногда есть список «Попутные задачи» — дела между делом, не из цели состояния.

- Берись за задачу, только если она к слову и условие «когда уместно» выполнено. Не вставляй её в лоб и не перебивай ответ на вопрос человека.
- За один ответ — не больше одной попутной задачи, и не вместе с вопросом о человеке между делом.
- Предложил — отметь «${SIDE_TASK_TOOL}» { id, status: "asked" }. Человек сделал сам или согласился и сделал — { id, status: "done" }. Задача с полем решается записью поля через «flow_note».
- Человек отказался или промолчал — не настаивай и не напоминай в тот же день: число попыток ограничено, оно указано в списке.
- Задачи нет в списке — она решена или попытки закончились: не возвращайся к ней.`;

export const sideTaskRules: FlowRulePart = (flow) => (hasSideTasks(flow) ? SIDE_TASK_RULES : null);
