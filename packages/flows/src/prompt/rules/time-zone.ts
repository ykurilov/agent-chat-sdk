import type { FlowRulePart } from "./rule-part";

// Как считаются дни и когда звать «flow_time_zone». Номер дня и местное время — в хвосте запроса, не здесь: так
// постоянная инструкция одинакова во все дни и кэш цел.

const TIME_ZONE_RULES = `## Дни и время

- Разговор идёт по дням. Какой сейчас день и сколько времени у человека — в конце запроса. Это служебная строка: человеку её не пересказывай.
- Дни считаются по часам человека. Человек назвал город или часовой пояс, а в служебной строке не его время — вызови «flow_time_zone» с поясом IANA, например Asia/Novosibirsk.
- Специально город не выспрашивай, если служебная строка этого не просит.`;

export const timeZoneRules: FlowRulePart = (flow) => (flow.schedule ? TIME_ZONE_RULES : null);
