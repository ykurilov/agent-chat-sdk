import type { AgentFlow } from "../format/flow-format";
import type { FlowRulePart } from "./rules/rule-part";
import { timeZoneRules } from "./rules/time-zone";
import { dayFrameRules } from "./rules/day-frame";
import { sideTaskRules } from "./rules/side-tasks";

/** Как агент ведёт разговор по сценарию. Текст не зависит от состояния: инструкция одна на весь чат (→ В9). */
const FLOW_RULES = `# Разговор по сценарию

Ты ведёшь разговор по сценарию. Текущее состояние — в последнем блоке «flow:state»: его название, цель, как себя вести и условия выхода. Действуй по нему, пока не придёт новая карточка состояния.

- Условие выхода словами выполнено — вызови «flow_exit» с номером условия из карточки и одной фразой «why»: почему ты так считаешь. Переход проверяет независимый судья.
- «flow_exit» ответил карточкой нового состояния — состояние сменилось: продолжай ответ уже по ней. Если в ответе есть «скажи ровно это: …» — напиши этот текст слово в слово.
- Судья не подтвердил или «уже проверяли» — продолжай разговор в текущем состоянии, не спорь и не заявляй снова, пока человек не ответит.
- Узнал то, что карточка просит узнать, — запиши через «flow_note».
- Спросили, что ты знаешь о человеке, или просят что-то забыть — пользуйся «client_card».
- Инструмент ответил «в этом состоянии недоступно» — не вызывай его, пока состояние не сменится.
- Служебное сообщение «Сработало: …» — переход случился без тебя: продолжай по новой карточке.

## Такт

- Один вопрос за раз, коротко. Не дави и не придумывай срочность.
- Не называй состояния, условия и судью: человек видит только разговор.
- Спросил о постороннем — ответь коротко и вернись к цели состояния.`;

/** Части правил по возможностям сценария, по порядку. Каждую делает свой модуль. */
export const FLOW_RULE_PARTS: readonly FlowRulePart[] = [timeZoneRules, dayFrameRules, sideTaskRules];

/**
 * Постоянная часть инструкции: как работает сценарий, правила такта, части по возможностям сценария и «Общее для всех
 * состояний» версии чата. Сценарий без новых полей — текст как в 0.48.
 */
export function flowRules(common: string, flow?: AgentFlow, parts: readonly FlowRulePart[] = FLOW_RULE_PARTS): string {
  const extra = flow ? parts.map((part) => part(flow)?.trim()).filter(Boolean) : [];
  const rules = [FLOW_RULES, ...extra].join("\n\n");
  const shared = common.trim();
  return shared ? `${rules}\n\n## Общее для всех состояний\n${shared}` : rules;
}
