import type { ServiceBlockFormat } from "@ykurilov/agent-chat-core";

/**
 * Служебные тексты сценария, которые модель может подделать в ответе: строки переходов, «скажи ровно это», карточка
 * клиента. `withChat` добавляет их в `agent.serviceBlocks`: подделку ядро вырезает до экрана и записи.
 * Строки сверяются строго по форме — обычная фраза «Сработало: …» в ответе не трогается. Карточки состояния здесь нет:
 * у неё нет надёжной последней строки, а вырезка до пустой строки оставила бы на экране её середину.
 */
export const FLOW_SERVICE_BLOCKS: readonly ServiceBlockFormat[] = [
  { name: "flow_policy", line: "[flow:policy]", match: /^\[flow:policy\]$/, until: /^\[\/flow:policy\]$/ },
  { name: "flow_advice", line: "[flow:advice]", match: /^\[flow:advice\]$/, until: /^\[\/flow:advice\]$/ },
  // `transitionNotice`: «Сработало: тишина 3 ч → «Напоминание».»
  { name: "flow_transition", line: "Сработало: ", match: /^Сработало: .+ → «[^»\n]*»\.$/ },
  // Ответ `flow_exit`: «Переход: «А» → «Б». Состояние сменилось, …»
  { name: "flow_switch", line: "Переход: «", match: /^Переход: «[^»\n]*» → «[^»\n]*»\. Состояние сменилось, продолжай по новой карточке\.$/ },
  { name: "flow_say_exactly", line: "Первое сообщение этого состояния — скажи ровно это: «", match: /^Первое сообщение этого состояния — скажи ровно это: «.*»$/ },
  // Карточка клиента кончается строкой «о чём спросить» (`questionLine`).
  {
    name: "flow_client_card",
    line: "Что известно о человеке (карточка клиента):",
    match: /^Что известно о человеке \(карточка клиента\):$/,
    until: /^(?:Сейчас не спрашивай ничего о человеке между делом|Сначала узнай: «|Давно не уточняли: «|Можно спросить между делом: «)/,
  },
];
